from playwright.sync_api import sync_playwright
B='/tmp/claude-0/-home-claude/23baac29-0d12-53fd-89ee-6f0a4956ec6e/scratchpad/br/'
d3=open(B+'npm/node_modules/d3/dist/d3.min.js').read()
def route(r):
    u=r.request.url
    if 'd3.min.js' in u: r.fulfill(body=d3,content_type='application/javascript')
    elif 'fonts.g' in u: r.fulfill(body='',content_type='text/css')
    else: r.continue_()
ok=lambda n,c:print('PASS' if c else 'FAIL',n)
with sync_playwright() as p:
    b=p.chromium.launch()
    for nm,vw,vh,mob,cs in [('desktop',1100,900,False,'light'),('phone',390,844,True,'dark')]:
        ctx=b.new_context(viewport={'width':vw,'height':vh},has_touch=mob,is_mobile=mob,color_scheme=cs);pg=ctx.new_page();errs=[]
        pg.on('pageerror',lambda e:errs.append(str(e)));pg.on('console',lambda m:errs.append(m.text) if m.type=='error' else None)
        pg.route('**/*',route);pg.goto('file://'+B+'tt_tap_morph.html');pg.wait_for_timeout(500)
        print('==',nm)
        ok('no errors on load',not errs)
        ok('41 ranked rows',pg.evaluate("document.querySelectorAll('#rk .rk-row').length")==41)
        ok('41 scatter dots',pg.evaluate("document.querySelectorAll('#cSc .dt').length")==41)
        ok('3 who rows',pg.evaluate("document.querySelectorAll('#cWho .wr').length")==3)
        ok('who shares sum ~100',pg.evaluate("[...document.querySelectorAll('#cWho .wb')].every(w=>Math.abs([...w.children].reduce((a,i)=>a+parseFloat(i.style.width),0)-100)<.1)"))
        ok('charts below map on phone' if mob else 'charts beside sheet on desktop',pg.evaluate("document.querySelector('#charts').getBoundingClientRect().top>document.querySelector('#mapbox').getBoundingClientRect().bottom-2"))
        pg.evaluate("document.querySelector('#rk .rk-row').scrollIntoView({block:'center'})");y1=pg.evaluate("scrollY")
        k=pg.evaluate("document.querySelector('#rk .rk-row').dataset.k")
        pg.evaluate("document.querySelector('#rk .rk-row').click()");pg.wait_for_timeout(700)
        s=pg.evaluate('__st()');ok('rank click focuses without morphing',s['cur']==k and not s['mor'])
        ok('no scroll yank',abs(pg.evaluate("scrollY")-y1)<4)
        ok('scatter label for focus',pg.evaluate("[...document.querySelectorAll('#scLb text')].length>0"))
        pg.evaluate("document.querySelector('#cSc .hit[data-k=ARI]').dispatchEvent(new MouseEvent('click',{bubbles:true}))");pg.wait_for_timeout(500)
        ok('scatter click selects ARI',pg.evaluate('__st()')['cur']=='ARI')
        pg.evaluate("window.__tap('PFT');window.__tap('MYO')");pg.wait_for_timeout(900)
        ok('selection block appears',pg.evaluate("document.querySelectorAll('#cWho .wblk').length")==2)
        pg.click('#cSc .scp button[data-p=PNM]');pg.wait_for_timeout(200)
        ok('PNM chip redraws',pg.evaluate("document.querySelectorAll('#cSc .dt').length")==41 and 'PNM' in pg.inner_text('#cSc'))
        ov=pg.evaluate("(()=>{const t=[...document.querySelectorAll('#scLb text')].map(e=>e.getBoundingClientRect());let n=0;for(let i=0;i<t.length;i++)for(let j=i+1;j<t.length;j++){const a=t[i],c=t[j];if(!(a.right<c.left||a.left>c.right||a.bottom<c.top||a.top>c.bottom))n++}return n})()")
        ok('no overlapping scatter labels',ov==0)
        ok('no h-scroll',not pg.evaluate('document.documentElement.scrollWidth>innerWidth'))
        ok('no errors at end',not errs)
        if errs:print(errs[:3])
        pg.evaluate("document.querySelector('#cWho').scrollIntoView()");pg.wait_for_timeout(300)
        ctx.close()
    b.close()
